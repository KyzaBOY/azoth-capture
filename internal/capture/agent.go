package capture

import (
	"encoding/json"
	"fmt"
	"regexp"
	"strings"

	"azoth/capture/internal/hooks"
)

// moduleName matches the game's file name in upstream's _common.js:
//
//	MODULE_NAME: "NewWorld.exe",
var moduleName = regexp.MustCompile(`MODULE_NAME:\s*"[^"]*"`)

// patchCommonJS returns src (upstream's _common.js) with the game's file name
// set to name, so the hooks find a renamed game in memory. It fails if the
// name is not there exactly once, which means upstream changed shape.
func patchCommonJS(src, name string) (string, error) {
	if n := len(moduleName.FindAllStringIndex(src, -1)); n != 1 {
		return "", fmt.Errorf("expected one MODULE_NAME in _common.js, found %d (upstream changed?)", n)
	}
	quoted, err := json.Marshal(name) // a JavaScript string, quotes escaped
	if err != nil {
		return "", err
	}
	out := moduleName.ReplaceAllLiteralString(src, "MODULE_NAME: "+string(quoted))
	return "// Patched copy generated by Azoth Capture: only MODULE_NAME differs from\n" +
		"// Aeternum-World's Tools/nw_capture/_common.js (AGPL-3.0). It is the file name\n" +
		"// of the game being captured.\n" + out, nil
}

// vasBlock matches the table of hardcoded addresses in upstream's
// _dtls_ledger.js:  const VAS = { SSL_read: '0x…', … };
var vasBlock = regexp.MustCompile(`(?s)const VAS = \{.*?\};`)

// patchLedgerJS returns src (upstream's _dtls_ledger.js) with the address
// table replaced by the addresses resolved from the game exe. It fails if the
// table is not there exactly once, which means upstream changed shape and this
// code must be reviewed before it is allowed to hook anything.
func patchLedgerJS(src string, a hooks.Addrs) (string, error) {
	if n := len(vasBlock.FindAllStringIndex(src, -1)); n != 1 {
		return "", fmt.Errorf("expected one `const VAS = {…};` block in _dtls_ledger.js, found %d (upstream changed?)", n)
	}
	table := fmt.Sprintf("const VAS = {\n"+
		"        SSL_read:    '0x%X',\n"+
		"        SSL_write:   '0x%X',\n"+
		"        nss_keylog:  '0x%X',\n"+
		"    };", a.SSLRead, a.SSLWrite, a.Keylog)
	out := vasBlock.ReplaceAllLiteralString(src, table)

	banner := "// Patched copy generated by Azoth Capture: only the VAS table below differs from\n" +
		"// Aeternum-World's Tools/nw_capture/_dtls_ledger.js (AGPL-3.0). The addresses were\n" +
		"// resolved from the game executable by signature (internal/hooks).\n"
	if !strings.HasPrefix(out, banner) {
		out = banner + out
	}
	return out, nil
}
